import { open } from './harness.mjs';
const { b, pg, errors } = await open();
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
await pg.evaluate(() => { const E = DiagramEditor; E.mutate(() => { const a = E.makeVertex('rect', 100, 100), c = E.makeVertex('rect', 400, 100); const e = E.makeEdge(); e.source = a.id; e.target = c.id; E.page().cells.push(a, c, e); }); window.__ev = []; for (const t of ['pointerdown', 'pointerup', 'click', 'dblclick']) document.addEventListener(t, (e) => window.__ev.push(t + ':' + (e.target.id || e.target.tagName)), true); });
await sleep(300);
const mid = await pg.evaluate(() => { const vr = document.querySelector('#viewport').getBoundingClientRect(); const sp = DiagramEditor.toScreen({ x: 320, y: 130 }); return { x: vr.left + sp.x, y: vr.top + sp.y }; });
await pg.mouse.click(mid.x, mid.y, { count: 1 }); await sleep(50);
await pg.mouse.click(mid.x, mid.y, { count: 2 }); await sleep(200);
console.log(await pg.evaluate(() => window.__ev.join(' ')));
console.log('editing?', await pg.evaluate(() => JSON.stringify({ ed: !!DiagramEditor.S.editing, n: DiagramEditor.page().cells.length })));
console.log(errors.join('\n') || 'no errors');
await b.close();
